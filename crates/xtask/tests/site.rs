use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

const XTASK: &str = env!("CARGO_BIN_EXE_xtask");
const SCRATCH_ROOT: &str = env!("CARGO_TARGET_TMPDIR");

const CLEAN: Option<i32> = Some(0);
const FINDINGS: Option<i32> = Some(1);
const USAGE_ERROR: Option<i32> = Some(2);

const CHECK: &str = "site";
const WRITE_TOKENS: &str = "site-tokens";

const TOKENS: &str = "design/system/tokens.css";
const DESIGN_MIRROR: &str = "design/system/tokens-dark.css";
const SITE_TOKENS: &str = "site/tokens.css";
const SITE_MIRROR: &str = "site/tokens-dark.css";

const LIGHT_BACKGROUND: &str = "#FFFFFF";
const DARK_BACKGROUND: &str = "#000000";
/// The tokens of a kit of three tokens. The dark block holds a value with a function and
/// commas, and a comment the mirror leaves out.
const KIT_TOKENS: &str = "/* The tokens of a small kit. */
:root {
  --color-bg: #FFFFFF;
  --space-1: 4px;
  --shadow-raised: 0 1px 2px rgba(17, 19, 24, 0.08);
}

@media (prefers-color-scheme: dark) {
  :root {
    /* color */
    --color-bg: #000000;
    --space-1: 4px;
    --shadow-raised: 0 1px 2px rgba(0, 0, 0, 0.4), 0 0 0 1px rgba(255, 255, 255, 0.04);
  }
}
";
/// What the dark block of [`KIT_TOKENS`] renders.
const KIT_MIRROR: &str =
    "/* Generated by `cargo xtask site-tokens .` from the dark block of tokens.css. Never edited by hand. */
:root {
  color-scheme: dark;
  --color-bg: #000000;
  --space-1: 4px;
  --shadow-raised: 0 1px 2px rgba(0, 0, 0, 0.4), 0 0 0 1px rgba(255, 255, 255, 0.04);
}
";
const LINES_OF_KIT_MIRROR: usize = 7;
/// Tokens with the light block alone.
const TOKENS_WITHOUT_DARK_BLOCK: &str = ":root {\n  --color-bg: #FFFFFF;\n}\n";

struct Workspace {
    root: PathBuf,
}

/// What a subcommand left behind: how it exited and what it reported.
struct XtaskRun {
    exit_code: Option<i32>,
    report: String,
}

impl Workspace {
    /// A workspace that holds the tokens of a kit and nothing derived from them.
    fn of_tokens(test_name: &str, tokens: &str) -> Self {
        let root = Path::new(SCRATCH_ROOT).join("site").join(test_name);
        if root.exists() {
            fs::remove_dir_all(&root).expect("the previous workspace is removed");
        }
        Self { root }.with_file(TOKENS, tokens)
    }

    /// A workspace whose derived files were written from the tokens of the small kit.
    fn with_written_tokens(test_name: &str) -> Self {
        let workspace = Self::of_tokens(test_name, KIT_TOKENS);
        let written = workspace.run(WRITE_TOKENS);
        assert_eq!(written.exit_code, CLEAN, "{}", written.report);
        workspace
    }

    fn with_file(self, relative_path: &str, contents: &str) -> Self {
        let path = self.root.join(relative_path);
        fs::create_dir_all(path.parent().expect("a file of the workspace has a parent directory"))
            .expect("the parent directory is created");
        fs::write(path, contents).expect("the file is written");
        self
    }

    fn text_of(&self, relative_path: &str) -> String {
        fs::read_to_string(self.root.join(relative_path)).expect("the file of the workspace is read")
    }

    /// Replaces the one place of the file that holds `from`.
    fn with_change(self, relative_path: &str, from: &str, to: &str) -> Self {
        let text = self.text_of(relative_path);
        assert_eq!(text.matches(from).count(), 1, "`{from}` in {relative_path}");
        let changed = text.replace(from, to);
        self.with_file(relative_path, &changed)
    }

    fn without_file(self, relative_path: &str) -> Self {
        fs::remove_file(self.root.join(relative_path)).expect("the file of the workspace is removed");
        self
    }

    fn run(&self, subcommand: &str) -> XtaskRun {
        let output = Command::new(XTASK)
            .arg(subcommand)
            .arg(&self.root)
            .output()
            .expect("xtask runs");
        XtaskRun {
            exit_code: output.status.code(),
            report: String::from_utf8(output.stderr).expect("the report is UTF-8"),
        }
    }

    /// How a finding names a file of the workspace and a line of it.
    fn place(&self, relative_path: &str, line: usize) -> String {
        format!("{}:{line}: ", self.root.join(relative_path).display())
    }

    /// How a finding names a file of the workspace, whatever its line.
    fn file(&self, relative_path: &str) -> String {
        format!("{}:", self.root.join(relative_path).display())
    }
}

impl XtaskRun {
    fn assert_reports(&self, place: &str) {
        assert_eq!(self.exit_code, FINDINGS, "{}", self.report);
        assert!(
            self.report.lines().any(|line| line.starts_with(place)),
            "expected a finding at `{place}` in:\n{}",
            self.report
        );
    }

    fn assert_reports_nothing_of(&self, file: &str) {
        assert!(
            !self.report.lines().any(|line| line.starts_with(file)),
            "expected nothing of `{file}` in:\n{}",
            self.report
        );
    }

    fn assert_clean(&self) {
        assert_eq!(self.exit_code, CLEAN, "{}", self.report);
        assert_eq!(self.report, "");
    }
}

#[test]
fn the_token_files_are_written_as_the_tokens_render_them_and_the_folder_is_created() {
    let workspace = Workspace::of_tokens("written", KIT_TOKENS);

    let written = workspace.run(WRITE_TOKENS);

    written.assert_clean();
    assert_eq!(workspace.text_of(DESIGN_MIRROR), KIT_MIRROR);
    assert_eq!(workspace.text_of(SITE_MIRROR), KIT_MIRROR);
    assert_eq!(workspace.text_of(SITE_TOKENS), KIT_TOKENS);
    workspace.run(CHECK).assert_clean();
}

#[test]
fn a_mirror_of_the_design_behind_the_dark_block_fails() {
    let workspace =
        Workspace::with_written_tokens("design-mirror-behind").with_change(TOKENS, DARK_BACKGROUND, "#111111");

    let checked = workspace.run(CHECK);

    checked.assert_reports(&workspace.file(DESIGN_MIRROR));
}

#[test]
fn a_mirror_of_the_site_edited_by_hand_fails() {
    let workspace = Workspace::with_written_tokens("site-mirror-edited");
    let edited = format!("{KIT_MIRROR}:root {{ --color-bg: #222222; }}\n");
    let workspace = workspace.with_file(SITE_MIRROR, &edited);

    let checked = workspace.run(CHECK);

    checked.assert_reports(&workspace.place(SITE_MIRROR, LINES_OF_KIT_MIRROR + 1));
    checked.assert_reports_nothing_of(&workspace.file(DESIGN_MIRROR));
    checked.assert_reports_nothing_of(&workspace.file(SITE_TOKENS));
}

#[test]
fn the_tokens_of_the_site_behind_the_tokens_of_the_kit_fail() {
    let workspace =
        Workspace::with_written_tokens("site-tokens-behind").with_change(TOKENS, LIGHT_BACKGROUND, "#EEEEEE");

    let checked = workspace.run(CHECK);

    checked.assert_reports(&workspace.file(SITE_TOKENS));
    checked.assert_reports_nothing_of(&workspace.file(DESIGN_MIRROR));
    checked.assert_reports_nothing_of(&workspace.file(SITE_MIRROR));
}

#[test]
fn a_derived_file_that_is_missing_fails() {
    let workspace = Workspace::with_written_tokens("missing").without_file(SITE_TOKENS);

    let checked = workspace.run(CHECK);

    checked.assert_reports(&workspace.place(SITE_TOKENS, 1));
}

#[test]
fn tokens_without_a_dark_block_fail_and_render_nothing() {
    let workspace = Workspace::of_tokens("no-dark-block", TOKENS_WITHOUT_DARK_BLOCK);

    let checked = workspace.run(CHECK);
    let written = workspace.run(WRITE_TOKENS);

    checked.assert_reports(&workspace.place(TOKENS, 1));
    written.assert_reports(&workspace.place(TOKENS, 1));
    assert!(!workspace.root.join(SITE_TOKENS).exists());
    assert!(!workspace.root.join(DESIGN_MIRROR).exists());
}

#[test]
fn a_subcommand_without_a_workspace_is_a_usage_error() {
    for subcommand in [CHECK, WRITE_TOKENS] {
        let output = Command::new(XTASK).arg(subcommand).output().expect("xtask runs");

        assert_eq!(output.status.code(), USAGE_ERROR, "{subcommand}");
    }
}
