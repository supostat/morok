use morok_style::States;

use crate::property_family::PropertyFamily;
use crate::pseudo_element::PseudoElement;
use crate::token_family::TokenFamily;

const GENERATED_NOTICE: &str = "<!-- Generated by `morok_css::subset_reference()`. Do not edit it by hand: \
                                `MOROK_UPDATE_GOLDEN=1 cargo test -p morok-css --test subset_reference` rewrites \
                                it. -->";
const TITLE: &str = "# The CSS subset\n\n\
                     Every list here is rendered from the table the compiler of stylesheets itself reads.";
const PROPERTIES: &str = "## Properties\n\n\
                          A rule declares these properties; the compiler refuses any other.";
const STATES: &str = "## States\n\n\
                      A selector requires a state of an element with one of these pseudo-classes; the compiler \
                      refuses any other.";
const PSEUDO_ELEMENTS: &str = "## Pseudo-elements\n\n\
                               A rule of a pseudo-element styles a part of its element and declares only what the \
                               pseudo-element takes.";
const TOKEN_FAMILIES: &str = "## Token families\n\n\
                              The name of a token opens, after `--`, with the prefix of its family:";

const PARAGRAPH_BREAK: &str = "\n\n";

/// The reference of the CSS subset as markdown, rendered from the tables the compiler reads: the
/// properties family by family with what each takes, the states, the pseudo-elements with what a
/// rule of theirs may set, and the families of tokens.
///
/// Its committed output is `docs/css-subset.md` of this crate.
pub fn subset_reference() -> String {
    let mut paragraphs = vec![GENERATED_NOTICE.to_owned(), TITLE.to_owned(), PROPERTIES.to_owned()];
    paragraphs.extend(PropertyFamily::ALL.iter().map(property_family));
    paragraphs.extend([
        STATES.to_owned(),
        states(),
        PSEUDO_ELEMENTS.to_owned(),
        pseudo_elements(),
        format!("{TOKEN_FAMILIES} {}.", TokenFamily::PREFIXES),
    ]);
    paragraphs.join(PARAGRAPH_BREAK) + "\n"
}

fn property_family(family: &PropertyFamily) -> String {
    let properties = family
        .properties
        .iter()
        .map(|property| format!("`{}` takes {}", property.name, property.expectation));
    format!("### {}{PARAGRAPH_BREAK}{}", family.title, list(properties))
}

fn states() -> String {
    list(
        States::PSEUDO_CLASSES
            .iter()
            .map(|(pseudo_class, _)| format!("`:{pseudo_class}`")),
    )
}

fn pseudo_elements() -> String {
    list(
        PseudoElement::ALL
            .iter()
            .map(|pseudo_element| format!("`::{}` takes {}", pseudo_element.name(), pseudo_element.expectation())),
    )
}

fn list(entries: impl Iterator<Item = String>) -> String {
    let lines: Vec<String> = entries.map(|entry| format!("- {entry}")).collect();
    lines.join("\n")
}
